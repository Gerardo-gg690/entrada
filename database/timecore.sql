CREATE DATABASE IF NOT EXISTS timecore CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE timecore;
CREATE TABLE IF NOT EXISTS admins (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(80) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS employees (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(140) NOT NULL,
 department VARCHAR(120) NULL,
 pin_hash VARCHAR(255) NOT NULL,
 active TINYINT(1) NOT NULL DEFAULT 1,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_employee_name(name)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS attendance (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 employee_id INT UNSIGNED NOT NULL,
 work_date DATE NOT NULL,
 clock_in DATETIME NULL,
 clock_out DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uq_employee_day(employee_id,work_date),
 CONSTRAINT fk_att_emp FOREIGN KEY(employee_id) REFERENCES employees(id) ON DELETE CASCADE,
 INDEX idx_work_date(work_date)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS settings (
 id TINYINT UNSIGNED PRIMARY KEY DEFAULT 1,
 salary DECIMAL(10,2) NOT NULL DEFAULT 408.00,
 half_salary DECIMAL(10,2) NOT NULL DEFAULT 204.00,
 paid_days TINYINT UNSIGNED NOT NULL DEFAULT 30,
 normal_hours DECIMAL(5,2) NOT NULL DEFAULT 8.00,
 extra_rate DECIMAL(10,2) NOT NULL DEFAULT 3.00,
 timezone VARCHAR(64) NOT NULL DEFAULT 'America/El_Salvador',
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
INSERT INTO settings(id) VALUES(1) ON DUPLICATE KEY UPDATE id=id;
